"""Several devices or book members can work on a book at once:

- Create is idempotent: the device generates the id when the user taps Save and re-sends it on retry.
- Edit is guarded by version: if another device saved in between, nothing is written (409).
- Balances need no locking: they are SUM(entries), so two devices adding at the same moment both count.
"""
from dataclasses import dataclass
from datetime import date, time
from uuid import UUID

from sqlalchemy import text
from sqlalchemy.orm import Session


class Conflict(Exception):
    """Another device changed or deleted this row first."""


@dataclass
class Entry:
    account_id: UUID
    amount: int  # signed


@dataclass
class TxnIn:
    id: UUID  # generated by the device
    book_id: UUID
    type: str
    occurred_on: date
    entries: list[Entry]
    category_id: UUID | None = None
    payee: str | None = None
    note: str | None = None
    occurred_time: time | None = None    # none: 00:00 on a new one, unchanged on an edit


def _insert_entries(db: Session, t: TxnIn) -> None:
    db.execute(
        text("insert into entries (book_id, transaction_id, account_id, amount)"
             " values (:b, :t, :a, :amt)"),
        [{"b": t.book_id, "t": t.id, "a": e.account_id, "amt": e.amount} for e in t.entries],
    )


def create_transaction(db: Session, t: TxnIn) -> int:
    """Returns the version. Safe to call again with the same id.
    created_by is filled in by the database from the signed-in user."""
    row = db.execute(
        text("insert into transactions (id, book_id, type, occurred_on, occurred_time, category_id, payee, note)"
             " values (:id, :b, :type, :d, coalesce(cast(:tm as time), '00:00'), :c, :p, :n)"
             " on conflict (id) do nothing returning version"),
        {"id": t.id, "b": t.book_id, "type": t.type, "d": t.occurred_on, "tm": t.occurred_time,
         "c": t.category_id, "p": t.payee, "n": t.note},
    ).first()
    if row is None:  # already saved by an earlier attempt
        existing = db.execute(text("select version from transactions where id = :id"), {"id": t.id}).first()
        if existing is None:
            raise Conflict("id already used")  # not in a book this user can see (RLS hides it)
        return existing.version
    _insert_entries(db, t)
    return row.version


def update_transaction(db: Session, t: TxnIn, expected_version: int) -> int:
    """Replace a transaction's header and entries. Returns the new version.

    Any change is a new version with its own line in the edit history,
    including one that only changes amounts or accounts: the entries live in
    their own table, which the version trigger on the header can't see, so
    the update then also sets modified_at, and bump_version() counts that as
    a change. Saving with nothing changed keeps the version. The entries are
    rewritten only when they changed, so a header edit or a save of nothing
    adds no entry rows to the audit log (nor moves the change marker for them);
    the shape check still runs, on the header's type. A purchase that is no longer an expense on its installment
    plan's card loses the plan."""
    saved = db.execute(text("select account_id, amount from entries where transaction_id = :id"), {"id": t.id}).all()
    entries_changed = sorted((r.account_id, r.amount) for r in saved) != sorted((e.account_id, e.amount) for e in t.entries)
    # The UPDATE locks the header row, so a second device or book member
    # editing at the same moment waits, then re-checks the version and matches
    # 0 rows. A viewer's UPDATE matches 0 rows too (RLS), which also ends as 409;
    # the API should check the role first to return 403 instead.
    row = db.execute(
        text("update transactions set type = :type, occurred_on = :d,"
             " occurred_time = coalesce(cast(:tm as time), occurred_time), category_id = :c, payee = :p, note = :n"
             + (", modified_at = now()" if entries_changed else "")
             + " where id = :id and version = :v returning version"),
        {"id": t.id, "v": expected_version, "type": t.type, "d": t.occurred_on, "tm": t.occurred_time,
         "c": t.category_id, "p": t.payee, "n": t.note},
    ).first()
    if row is None:
        raise Conflict("changed or deleted on another device")
    if entries_changed:
        db.execute(text("delete from entries where transaction_id = :id"), {"id": t.id})
        _insert_entries(db, t)
    db.execute(text(
        "delete from installment_plans p where p.transaction_id = :id and not exists ("
        " select 1 from transactions t join entries e on e.transaction_id = t.id"
        "  where t.id = p.transaction_id and t.type = 'expense' and e.account_id = p.account_id"
        "    and (select count(*) from entries x where x.transaction_id = t.id) = 1)"), {"id": t.id})
    return row.version


def delete_transaction(db: Session, id: UUID, expected_version: int) -> None:
    n = db.execute(text("delete from transactions where id = :id and version = :v"),
                   {"id": id, "v": expected_version}).rowcount
    if n == 0:
        raise Conflict("changed or deleted on another device")
