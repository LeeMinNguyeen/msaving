"""Books: create (with starter categories), list, settings, delete.

Ids come from the client, so a retried create can't make a second book. Edits
send the version the client loaded; a mismatch is 409 (msaving-docs, Several
devices at once).
"""
from datetime import datetime
from typing import Literal
from uuid import UUID

from fastapi import APIRouter, Depends, HTTPException, Response
from pydantic import BaseModel
from sqlalchemy import text
from sqlalchemy.orm import Session

from app.api.deps import get_db
from app.api.models import CurrencyCode, Name, Timezone
from app.core.auth import current_user
from app.domain.book_setup import add_starter_categories

router = APIRouter(prefix="/books")


class Book(BaseModel):
    id: UUID
    name: str
    base_currency: str
    timezone: str
    role: Literal["owner", "editor", "viewer"]
    archived_at: datetime | None
    version: int


BOOK = ("select b.id, b.name, b.base_currency, b.timezone, m.role::text as role, b.archived_at, b.version"
        "  from books b join book_members m on m.book_id = b.id"
        " where m.user_id = current_app_user() and m.accepted_at is not null")


def get_book(db: Session, book_id: UUID) -> Book:
    row = db.execute(text(BOOK + " and b.id = :b"), {"b": book_id}).mappings().first()
    if row is None:
        raise HTTPException(404, "not_found")
    return Book(**row)


def require_role(book: Book, *roles: str) -> None:
    if book.role not in roles:
        raise HTTPException(403, "forbidden")


@router.get("")
def list_books(db: Session = Depends(get_db)) -> list[Book]:
    return [Book(**r) for r in db.execute(text(BOOK + " order by b.archived_at nulls first, b.created_at")).mappings()]


class CreateBook(BaseModel):
    id: UUID                                   # generated by the client
    name: Name
    base_currency: CurrencyCode
    timezone: Timezone
    starter_categories: bool = True            # the "Add starter categories" tick, on by default


@router.post("", status_code=201)
def create_book(body: CreateBook, user_id: UUID = Depends(current_user), db: Session = Depends(get_db)) -> Book:
    # A retry finds the book made the first time. Otherwise a plain insert: no
    # RETURNING and no ON CONFLICT, since both make Postgres apply the read
    # policy to the new row, and the creator only becomes a member once the
    # insert finishes (msaving-docs, Users and shared books). An id that belongs to
    # a book this user can't see fails on the primary key: 409.
    if db.execute(text("select 1 from books where id = :i"), {"i": body.id}).first() is None:
        db.execute(text("insert into books (id, created_by, name, base_currency, timezone) values (:i, :u, :n, :c, :tz)"),
                   {"i": body.id, "u": user_id, "n": body.name, "c": body.base_currency, "tz": body.timezone})
        if body.starter_categories:
            language = db.execute(text("select language from my_profile()")).scalar() or "vi"
            add_starter_categories(db, body.id, language)
    db.commit()
    return get_book(db, body.id)


@router.get("/{book_id}")
def read_book(book_id: UUID, db: Session = Depends(get_db)) -> Book:
    return get_book(db, book_id)


class UpdateBook(BaseModel):
    version: int
    name: Name | None = None
    base_currency: CurrencyCode | None = None  # converts the book's budgets at today's rate; refused without one (no_rate)
    timezone: Timezone | None = None
    archived: bool | None = None


@router.patch("/{book_id}")
def update_book(book_id: UUID, body: UpdateBook, db: Session = Depends(get_db)) -> Book:
    require_role(get_book(db, book_id), "owner")
    n = db.execute(text("update books set name = coalesce(:n, name), base_currency = coalesce(:c, base_currency),"
                        " timezone = coalesce(:tz, timezone),"
                        " archived_at = case when cast(:a as boolean) is null then archived_at when cast(:a as boolean) then coalesce(archived_at, now()) end"
                        " where id = :b and version = :v"),
                   {"b": book_id, "v": body.version, "n": body.name, "c": body.base_currency, "tz": body.timezone,
                    "a": body.archived}).rowcount
    if n == 0:
        raise HTTPException(409, "conflict")
    db.commit()
    return get_book(db, book_id)


@router.delete("/{book_id}", status_code=204)
def delete_book(book_id: UUID, version: int, db: Session = Depends(get_db)) -> Response:
    """Deletes the book and everything in it, its audit log included."""
    require_role(get_book(db, book_id), "owner")
    if db.execute(text("delete from books where id = :b and version = :v"), {"b": book_id, "v": version}).rowcount == 0:
        raise HTTPException(409, "conflict")
    db.commit()
    return Response(status_code=204)
