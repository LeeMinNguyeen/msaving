"""Credit card purchases paid in installments. The schedule and what each bill asks for: app/domain/bills.py."""
from datetime import date, datetime
from typing import Annotated
from uuid import UUID
from zoneinfo import ZoneInfo

from fastapi import APIRouter, Depends, HTTPException, Response
from pydantic import BaseModel, Field
from sqlalchemy import text
from sqlalchemy.orm import Session

from app.api.deps import get_db
from app.api.routes.v1.books import get_book, require_role
from app.domain.bills import installment_plans, next_on_or_after

router = APIRouter(prefix="/books/{book_id}/installments")

Months = Annotated[int, Field(ge=2, le=60)]
Fee = Annotated[int, Field(ge=0, le=10**15)]


class Plan(BaseModel):
    id: UUID
    account_id: UUID
    transaction_id: UUID
    payee: str | None
    occurred_on: date
    amount: int                 # the purchase, positive
    months: int
    converted_on: date
    first_statement: date
    fee: int
    fee_split: bool
    counts_toward_limit: bool
    ended_on: date | None
    version: int
    installment: int            # the first installments' amount; the last takes what's left
    billed: int                 # installments billed by the statements so far
    left_to_bill: int


def _plans(db: Session, book_id: UUID) -> list[Plan]:
    book = get_book(db, book_id)
    return [Plan(**p) for p in installment_plans(db, book_id, datetime.now(ZoneInfo(book.timezone)).date())]


def _plan(db: Session, book_id: UUID, plan_id: UUID) -> Plan:
    found = next((p for p in _plans(db, book_id) if p.id == plan_id), None)
    if found is None:
        raise HTTPException(404, "not_found")
    return found


@router.get("")
def list_plans(book_id: UUID, db: Session = Depends(get_db)) -> list[Plan]:
    return _plans(db, book_id)


class CreatePlan(BaseModel):
    id: UUID                    # generated by the client
    transaction_id: UUID
    months: Months
    converted_on: date | None = None        # default: the purchase's date
    first_statement: date | None = None     # default: the statement the conversion date falls in
    fee: Fee = 0
    fee_split: bool = False
    counts_toward_limit: bool = True


@router.post("", status_code=201)
def create_plan(book_id: UUID, body: CreatePlan, db: Session = Depends(get_db)) -> Plan:
    require_role(get_book(db, book_id), "owner", "editor")
    purchase = db.execute(text(
        "select t.occurred_on, a.statement_day from transactions t join entries e on e.transaction_id = t.id"
        "  join accounts a on a.id = e.account_id where t.id = :t and t.book_id = :b limit 1"),
        {"t": body.transaction_id, "b": book_id}).mappings().first()
    if purchase is None:
        raise HTTPException(404, "not_found")
    converted = body.converted_on or purchase["occurred_on"]
    first = body.first_statement or (next_on_or_after(converted, purchase["statement_day"]) if purchase["statement_day"] else converted)
    db.execute(text(
        "insert into installment_plans (id, book_id, account_id, transaction_id, months, converted_on, first_statement,"
        "                               fee, fee_split, counts_toward_limit)"
        " select :i, :b, e.account_id, :t, :m, :c, :f, :fee, :split, :counts from entries e where e.transaction_id = :t limit 1"
        " on conflict (id) do nothing"),
        {"i": body.id, "b": book_id, "t": body.transaction_id, "m": body.months, "c": converted, "f": first,
         "fee": body.fee, "split": body.fee_split, "counts": body.counts_toward_limit})
    db.commit()
    return _plan(db, book_id, body.id)


class UpdatePlan(BaseModel):
    version: int
    months: Months | None = None
    converted_on: date | None = None
    first_statement: date | None = None
    fee: Fee | None = None
    fee_split: bool | None = None
    counts_toward_limit: bool | None = None
    ended_on: date | None = None            # sent as null: not ended


@router.patch("/{plan_id}")
def update_plan(book_id: UUID, plan_id: UUID, body: UpdatePlan, db: Session = Depends(get_db)) -> Plan:
    require_role(get_book(db, book_id), "owner", "editor")
    _plan(db, book_id, plan_id)
    fields = {k: getattr(body, k) for k in body.model_fields_set - {"version"}}
    if any(v is None for k, v in fields.items() if k != "ended_on"):
        raise HTTPException(422, "invalid")
    sets = ", ".join(f"{k} = :{k}" for k in fields) or "version = version"
    n = db.execute(text(f"update installment_plans set {sets} where id = :i and book_id = :b and version = :v"),
                   {**fields, "i": plan_id, "b": book_id, "v": body.version}).rowcount
    if n == 0:
        raise HTTPException(409, "conflict")
    db.commit()
    return _plan(db, book_id, plan_id)


@router.delete("/{plan_id}", status_code=204)
def delete_plan(book_id: UUID, plan_id: UUID, version: int, db: Session = Depends(get_db)) -> Response:
    require_role(get_book(db, book_id), "owner", "editor")
    _plan(db, book_id, plan_id)
    if db.execute(text("delete from installment_plans where id = :i and book_id = :b and version = :v"),
                  {"i": plan_id, "b": book_id, "v": version}).rowcount == 0:
        raise HTTPException(409, "conflict")
    db.commit()
    return Response(status_code=204)
