"""Categories in a book: a tree (parent_id), kinds expense / income / transfer.

Transfer categories are labels only: spending, budgets and AI summaries select
by transaction type, so they never count. Deleting a category that has
transactions archives it instead (its history keeps pointing at it) and says so.
"""
from datetime import datetime
from typing import Annotated, Literal
from uuid import UUID

from fastapi import APIRouter, Depends, HTTPException
from psycopg import errors as pg
from pydantic import BaseModel, StringConstraints
from sqlalchemy import text
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from app.api.deps import get_db
from app.api.models import Name
from app.api.routes.v1.books import get_book, require_role

router = APIRouter(prefix="/books/{book_id}/categories")

Kind = Literal["expense", "income", "transfer"]
Color = Annotated[str, StringConstraints(to_lower=True, pattern=r"^#[0-9a-fA-F]{6}$")]


class Category(BaseModel):
    id: UUID
    parent_id: UUID | None
    name: str
    kind: Kind
    color: str | None
    archived_at: datetime | None
    version: int


CATEGORY = "select id, parent_id, name, kind, color, archived_at, version from categories where book_id = :book"


def get_category(db: Session, book_id: UUID, category_id: UUID) -> Category:
    row = db.execute(text(CATEGORY + " and id = :c"), {"book": book_id, "c": category_id}).mappings().first()
    if row is None:
        raise HTTPException(404, "not_found")
    return Category(**row)


@router.get("")
def list_categories(book_id: UUID, include_archived: bool = False, db: Session = Depends(get_db)) -> list[Category]:
    get_book(db, book_id)
    sql = CATEGORY + ("" if include_archived else " and archived_at is null") + " order by kind, name"
    return [Category(**r) for r in db.execute(text(sql), {"book": book_id}).mappings()]


class CreateCategory(BaseModel):
    id: UUID                                   # generated by the client
    name: Name
    kind: Kind
    parent_id: UUID | None = None
    color: Color | None = None


@router.post("", status_code=201)
def create_category(book_id: UUID, body: CreateCategory, db: Session = Depends(get_db)) -> Category:
    require_role(get_book(db, book_id), "owner", "editor")
    db.execute(text("insert into categories (id, book_id, parent_id, name, kind, color) values (:i, :b, :p, :n, :k, :c)"
                    " on conflict (id) do nothing"),
               {"i": body.id, "b": book_id, "p": body.parent_id, "n": body.name, "k": body.kind, "c": body.color})
    db.commit()
    return get_category(db, book_id, body.id)


class UpdateCategory(BaseModel):
    version: int
    name: Name | None = None
    kind: Kind | None = None                   # to or from transfer is refused once used (category_kind)
    parent_id: UUID | None = None
    top_level: bool = False                    # true = move to the top (parent_id can't say "none" on its own)
    color: Color | Literal[""] | None = None   # "" = the app's default colour
    archived: bool | None = None


@router.patch("/{category_id}")
def update_category(book_id: UUID, category_id: UUID, body: UpdateCategory, db: Session = Depends(get_db)) -> Category:
    require_role(get_book(db, book_id), "owner", "editor")
    get_category(db, book_id, category_id)
    if body.parent_id is not None:
        loop = db.execute(text("select 1 from category_ancestors where category_id = :p and ancestor_id = :c"),
                          {"p": body.parent_id, "c": category_id}).first()
        if loop:                               # under itself or one of its own sub-categories
            raise HTTPException(422, "invalid")
    n = db.execute(text(
        "update categories set name = coalesce(:n, name), kind = coalesce(:k, kind),"
        " parent_id = case when cast(:top as boolean) then null else coalesce(cast(:p as uuid), parent_id) end,"
        " color = case when cast(:c as text) is null then color when cast(:c as text) = '' then null else cast(:c as text) end,"
        " archived_at = case when cast(:a as boolean) is null then archived_at"
        "                    when cast(:a as boolean) then coalesce(archived_at, now()) end"
        " where id = :i and book_id = :b and version = :v"),
        {"i": category_id, "b": book_id, "v": body.version, "n": body.name, "k": body.kind, "p": body.parent_id,
         "top": body.top_level, "c": body.color, "a": body.archived}).rowcount
    if n == 0:
        raise HTTPException(409, "conflict")
    db.commit()
    return get_category(db, book_id, category_id)


class Deleted(BaseModel):
    deleted: bool
    archived: bool                             # true = it had transactions, so it was archived instead


@router.delete("/{category_id}")
def delete_category(book_id: UUID, category_id: UUID, version: int, db: Session = Depends(get_db)) -> Deleted:
    require_role(get_book(db, book_id), "owner", "editor")
    get_category(db, book_id, category_id)
    try:
        with db.begin_nested():
            n = db.execute(text("delete from categories where id = :i and book_id = :b and version = :v"),
                           {"i": category_id, "b": book_id, "v": version}).rowcount
    except IntegrityError as e:
        if not isinstance(e.orig, pg.ForeignKeyViolation):
            raise
        if e.orig.diag.constraint_name == "categories_parent_id_book_id_fkey":
            raise HTTPException(409, "has_subcategories") from None
        n = db.execute(text("update categories set archived_at = coalesce(archived_at, now())"
                            " where id = :i and book_id = :b and version = :v"),
                       {"i": category_id, "b": book_id, "v": version}).rowcount
        if n == 0:
            raise HTTPException(409, "conflict") from None
        db.commit()
        return Deleted(deleted=False, archived=True)
    if n == 0:
        raise HTTPException(409, "conflict")
    db.commit()
    return Deleted(deleted=True, archived=False)
