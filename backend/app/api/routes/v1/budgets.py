"""Budgets: a limit for one expense category per period (daily, weekly,
monthly, quarterly, yearly), in the book's currency. Sub-categories count
toward their parent. Progress comes from budget_progress, in the book's
time zone; budgets outside their start/end dates or on archived categories
have none."""
from datetime import date
from typing import Annotated, Literal
from uuid import UUID

from fastapi import APIRouter, Depends, HTTPException, Response
from pydantic import BaseModel, Field
from sqlalchemy import text
from sqlalchemy.orm import Session

from app.api.deps import get_db
from app.api.routes.v1.books import get_book, require_role

router = APIRouter(prefix="/books/{book_id}/budgets")

Period = Literal["daily", "weekly", "monthly", "quarterly", "yearly"]
Amount = Annotated[int, Field(gt=0)]           # minor units of the book's currency


class Progress(BaseModel):
    period_start: date
    period_end: date
    spent: int
    remaining: int
    percent_used: float
    not_converted: int                         # transactions left out for lack of a rate


class Budget(BaseModel):
    id: UUID
    category_id: UUID
    period: Period
    amount: int
    starts_on: date
    ends_on: date | None
    version: int
    progress: Progress | None                  # None outside its dates or on an archived category


BUDGET = """
select b.id, b.category_id, b.period::text as period, b.amount, b.starts_on, b.ends_on, b.version,
       case when p.budget_id is null then null else jsonb_build_object(
         'period_start', p.period_start, 'period_end', p.period_end, 'spent', p.spent, 'remaining', p.remaining,
         'percent_used', p.percent_used, 'not_converted', p.not_converted) end as progress
  from budgets b left join budget_progress p on p.budget_id = b.id
 where b.book_id = :book"""


def get_budget(db: Session, book_id: UUID, budget_id: UUID) -> Budget:
    row = db.execute(text(BUDGET + " and b.id = :i"), {"book": book_id, "i": budget_id}).mappings().first()
    if row is None:
        raise HTTPException(404, "not_found")
    return Budget(**row)


@router.get("")
def list_budgets(book_id: UUID, db: Session = Depends(get_db)) -> list[Budget]:
    get_book(db, book_id)
    return [Budget(**r) for r in db.execute(text(BUDGET + " order by b.category_id, b.period"), {"book": book_id}).mappings()]


class CreateBudget(BaseModel):
    id: UUID                                   # generated by the client
    category_id: UUID
    period: Period
    amount: Amount
    starts_on: date | None = None              # default: today
    ends_on: date | None = None


@router.post("", status_code=201)
def create_budget(book_id: UUID, body: CreateBudget, db: Session = Depends(get_db)) -> Budget:
    require_role(get_book(db, book_id), "owner", "editor")
    db.execute(text("insert into budgets (id, book_id, category_id, period, amount, starts_on, ends_on)"
                    " values (:i, :b, :c, cast(:p as budget_period), :a,"
                    "         coalesce(cast(:s as date), (now() at time zone (select timezone from books where id = :b))::date), :e)"
                    " on conflict (id) do nothing"),
               {"i": body.id, "b": book_id, "c": body.category_id, "p": body.period, "a": body.amount,
                "s": body.starts_on, "e": body.ends_on})
    db.commit()
    return get_budget(db, book_id, body.id)


class UpdateBudget(BaseModel):
    version: int
    amount: Amount | None = None
    starts_on: date | None = None
    ends_on: date | None = None
    ongoing: bool = False                      # true = clear ends_on


@router.patch("/{budget_id}")
def update_budget(book_id: UUID, budget_id: UUID, body: UpdateBudget, db: Session = Depends(get_db)) -> Budget:
    require_role(get_book(db, book_id), "owner", "editor")
    get_budget(db, book_id, budget_id)
    n = db.execute(text(
        "update budgets set amount = coalesce(:a, amount), starts_on = coalesce(cast(:s as date), starts_on),"
        " ends_on = case when cast(:o as boolean) then null else coalesce(cast(:e as date), ends_on) end"
        " where id = :i and book_id = :b and version = :v"),
        {"i": budget_id, "b": book_id, "v": body.version, "a": body.amount, "s": body.starts_on, "e": body.ends_on,
         "o": body.ongoing}).rowcount
    if n == 0:
        raise HTTPException(409, "conflict")
    db.commit()
    return get_budget(db, book_id, budget_id)


@router.delete("/{budget_id}", status_code=204)
def delete_budget(book_id: UUID, budget_id: UUID, version: int, db: Session = Depends(get_db)) -> Response:
    require_role(get_book(db, book_id), "owner", "editor")
    get_budget(db, book_id, budget_id)
    if db.execute(text("delete from budgets where id = :i and book_id = :b and version = :v"),
                  {"i": budget_id, "b": book_id, "v": version}).rowcount == 0:
        raise HTTPException(409, "conflict")
    db.commit()
    return Response(status_code=204)
