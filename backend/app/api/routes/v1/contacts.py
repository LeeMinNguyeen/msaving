"""People in a book, for lending and borrowing: a name and a note, nothing else, since they never signed up. They're
never sent to the AI."""
from datetime import datetime
from typing import Annotated, Literal
from uuid import UUID

from fastapi import APIRouter, Depends, HTTPException
from psycopg import errors as pg
from pydantic import BaseModel, StringConstraints
from sqlalchemy import text
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from app.api.deps import get_db
from app.api.models import Name
from app.api.routes.v1.books import get_book, require_role

router = APIRouter(prefix="/books/{book_id}/contacts")

Note = Annotated[str, StringConstraints(strip_whitespace=True, max_length=500)]


class Balance(BaseModel):
    currency: str
    owed_to_you: int
    you_owe: int


class Contact(BaseModel):
    id: UUID
    name: str
    note: str | None
    archived_at: datetime | None
    version: int
    balances: list[Balance]                    # one per currency with a lent or loan account


CONTACT = """
select c.id, c.name, c.note, c.archived_at, c.version,
       coalesce((select jsonb_agg(jsonb_build_object('currency', cb.currency, 'owed_to_you', cb.owed_to_you, 'you_owe', cb.you_owe)
                                  order by cb.currency)
                   from contact_balances cb where cb.contact_id = c.id and cb.currency is not null), '[]') as balances
  from contacts c where c.book_id = :book"""


def get_contact(db: Session, book_id: UUID, contact_id: UUID) -> Contact:
    row = db.execute(text(CONTACT + " and c.id = :c"), {"book": book_id, "c": contact_id}).mappings().first()
    if row is None:
        raise HTTPException(404, "not_found")
    return Contact(**row)


@router.get("")
def list_contacts(book_id: UUID, include_archived: bool = False, db: Session = Depends(get_db)) -> list[Contact]:
    get_book(db, book_id)
    sql = CONTACT + ("" if include_archived else " and c.archived_at is null") + " order by c.name"
    return [Contact(**r) for r in db.execute(text(sql), {"book": book_id}).mappings()]


class CreateContact(BaseModel):
    id: UUID                                   # generated by the client
    name: Name
    note: Note | None = None


@router.post("", status_code=201)
def create_contact(book_id: UUID, body: CreateContact, db: Session = Depends(get_db)) -> Contact:
    require_role(get_book(db, book_id), "owner", "editor")
    db.execute(text("insert into contacts (id, book_id, name, note) values (:i, :b, :n, :o) on conflict (id) do nothing"),
               {"i": body.id, "b": book_id, "n": body.name, "o": body.note or None})
    db.commit()
    return get_contact(db, book_id, body.id)


class UpdateContact(BaseModel):
    version: int
    name: Name | None = None
    note: Note | Literal[""] | None = None     # "" clears it
    archived: bool | None = None


@router.patch("/{contact_id}")
def update_contact(book_id: UUID, contact_id: UUID, body: UpdateContact, db: Session = Depends(get_db)) -> Contact:
    require_role(get_book(db, book_id), "owner", "editor")
    get_contact(db, book_id, contact_id)
    n = db.execute(text(
        "update contacts set name = coalesce(:n, name),"
        " note = case when cast(:o as text) is null then note when cast(:o as text) = '' then null else cast(:o as text) end,"
        " archived_at = case when cast(:a as boolean) is null then archived_at"
        "                    when cast(:a as boolean) then coalesce(archived_at, now()) end"
        " where id = :i and book_id = :b and version = :v"),
        {"i": contact_id, "b": book_id, "v": body.version, "n": body.name, "o": body.note, "a": body.archived}).rowcount
    if n == 0:
        raise HTTPException(409, "conflict")
    db.commit()
    return get_contact(db, book_id, contact_id)


class Deleted(BaseModel):
    deleted: bool
    archived: bool                             # true = linked to an account, so archived instead


@router.delete("/{contact_id}")
def delete_contact(book_id: UUID, contact_id: UUID, version: int, db: Session = Depends(get_db)) -> Deleted:
    require_role(get_book(db, book_id), "owner", "editor")
    get_contact(db, book_id, contact_id)
    params = {"i": contact_id, "b": book_id, "v": version}
    try:
        with db.begin_nested():
            n = db.execute(text("delete from contacts where id = :i and book_id = :b and version = :v"), params).rowcount
    except IntegrityError as e:
        if not isinstance(e.orig, pg.ForeignKeyViolation):
            raise
        n = db.execute(text("update contacts set archived_at = coalesce(archived_at, now())"
                            " where id = :i and book_id = :b and version = :v"), params).rowcount
        if n == 0:
            raise HTTPException(409, "conflict") from None
        db.commit()
        return Deleted(deleted=False, archived=True)
    if n == 0:
        raise HTTPException(409, "conflict")
    db.commit()
    return Deleted(deleted=True, archived=False)
